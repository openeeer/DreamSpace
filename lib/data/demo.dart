import '../models/dream.dart';

List<Dream> demoDreams(DateTime now) {
  const titles = [
    'Лунная библиотека',
    'Океан без конца',
    'Красный лес',
    'Пустой город',
    'Стеклянная лестница',
    'Последний поезд',
    'Небесные острова',
    'Дверь под водой',
  ];
  const descriptions = [
    'Я оказался в библиотеке, которая парила над облаками. За высокими окнами сияла огромная Луна. Книги сами раскрывались и тихо перелетали с полки на полку.\n\nЯ поднялся по тёплой светящейся лестнице. Каждая ступень отзывалась знакомым воспоминанием. На самом верху лежала книга с моим именем, но все её страницы были ещё пусты. Я понял, что могу написать продолжение этого сна сам.',
    'Лодка покачивалась посреди бесконечного океана. Вода была настолько прозрачной, что в ней отражались даже далёкие звёзды.\n\nЯ не знал, куда плыву, и впервые это совершенно не тревожило. Луна опустилась к горизонту, оставив серебряную дорожку. Из глубины доносилась музыка, которую я будто слышал в детстве.',
    'В лесу все листья были красными, а тени — синими. Незнакомец в длинном пальто шёл впереди и оставлял за собой крошечные огоньки.\n\nМежду двумя деревьями стояла дверь. Я потянулся к ручке, но лес медленно повернулся вокруг меня, и дверь оказалась совсем в другой стороне.',
    'Город был совершенно пуст. В окнах горел свет, на столиках кафе стояли чашки с ещё горячим чаем, но людей нигде не было.\n\nВ витрине я заметил незнакомца. Когда обернулся, улица снова оказалась пустой. Только моё отражение в зеркале улыбнулось на секунду позже меня.',
    'Прозрачная лестница уходила прямо в ночное небо. Под ногами были видны облака, но стекло казалось надёжным и тёплым.\n\nВместо последней ступени висело зеркало. В нём отражалась Луна, хотя за моей спиной её не было. Я коснулся отражения, и по стеклу разошлись круги, словно по воде.',
    'На вокзале объявили последний поезд, но не назвали направление. Старые часы стояли на месте. Незнакомый попутчик протянул мне билет без даты.\n\nИз тёплого окна вагона я смотрел, как платформа исчезает в тумане. Было немного грустно, словно я прощался с местом, в котором никогда не бывал.',
    'В небе плавали острова. На самом маленьком росло огромное дерево, а его корни светились мягким золотым светом.\n\nЯ мог перелетать с одного острова на другой, просто представляя следующий шаг. Водопады растворялись в облаках. Я засмеялся, и звёзды ответили тихим звоном.',
    'На дне океана стояла деревянная дверь. За ней горел тёплый свет. Я мог дышать под водой и слышал каждый пузырёк так ясно, будто он был колокольчиком.\n\nК двери вела короткая лестница. Когда я открыл её, за порогом оказался берег того же океана — только над водой уже занимался рассвет.',
  ];
  const symbols = [
    ['Луна', 'Лестница', 'Книга'],
    ['Вода', 'Луна'],
    ['Дверь', 'Дерево'],
    ['Зеркало'],
    ['Лестница', 'Луна', 'Зеркало'],
    ['Поезд', 'Часы'],
    ['Луна', 'Дерево'],
    ['Вода', 'Дверь', 'Лестница'],
  ];
  const places = [
    'Библиотека',
    'Океан',
    'Лес',
    'Город',
    'Небо',
    'Вокзал',
    'Небо',
    'Океан',
  ];
  const moods = [
    Mood.calm,
    Mood.peaceful,
    Mood.strange,
    Mood.anxious,
    Mood.mysterious,
    Mood.sad,
    Mood.happy,
    Mood.mysterious,
  ];
  return List.generate(8, (i) {
    final date = DateTime(now.year, now.month, now.day - (i == 7 ? 6 : i));
    DreamElement element(String name, ElementKind kind) => DreamElement(
      id: 'demo-${kind.name}-${normalize(name)}',
      name: name,
      kind: kind,
    );
    return Dream(
      id: 'demo-$i',
      title: titles[i],
      description: descriptions[i],
      date: date,
      createdAt: now.toUtc().subtract(Duration(hours: i)),
      updatedAt: now.toUtc(),
      mood: moods[i],
      type: [0, 6].contains(i) ? DreamType.lucid : DreamType.normal,
      recurring: i == 4,
      lucidity: i == 0 ? 90 : 25 + i * 8,
      vividness: 95 - i * 4,
      theme: i.isEven ? DreamTheme.fantasy : DreamTheme.surreal,
      artwork: artworkIds[i],
      demo: true,
      favorite: i == 0,
      elements: [
        ...symbols[i].map((s) => element(s, ElementKind.symbol)),
        element(places[i], ElementKind.place),
        if ([2, 3, 5].contains(i)) element('Незнакомец', ElementKind.character),
      ],
    );
  });
}
